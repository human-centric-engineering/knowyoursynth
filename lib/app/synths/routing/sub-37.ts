/**
 * Moog Sub 37 signal routing, projected from its spec (`.context/app/synth-data/sub-37/sub-37.synth.json`, 0.11.0):
 * block and edge ids are the spec's module and connection ids; switches, levels and jacks are the definition's
 * (`defs/sub-37.ts`).
 *
 * Two oscillators, the sub oscillator an octave under Osc 1, noise and the feedback channel into the mixer, the ladder
 * filter, MultiDrive and the VCA. Each mod bus takes its LFO (or the filter envelope at F.EG/PGM) to pitch, cutoff and
 * its switched destination; the mod wheel, velocity and aftertouch set its depth. The pitch wheel's two edges are
 * omitted, as the app has no pitch bend, and so are the sequencer's per-step mod values, which are not modelled.
 */
import type { RoutingEdge, RoutingWhen, SynthRouting } from '@/lib/app/synths/contract';

const LFO_WAVES = ['triangle', 'square', 'saw', 'ramp', 'sample_hold'];

/** The edges of one mod bus, by the spec's connection ids for it. */
function busEdges(n: 1 | 2, ids: string[]): RoutingEdge[] {
  const m = `mod${n}`;
  const other = n === 1 ? 'lfo2' : 'lfo1';
  const dest = (d: string[]): RoutingWhen => ({ id: `${m}.dest`, in: d });
  const egTime: RoutingWhen = {
    all: [dest(['eg_time_pgm']), { id: `${m}.pgmDst`, eq: 'eg_time' }],
  };
  const amt = [{ id: `${m}.modAmt`, off: 0 }];
  const [lfo, feg, wheel, vel, at, p1, p2, cut, rate, vca, w1, w2, noise, tf, ta, reset] = ids;
  return [
    { id: lfo, from: `lfo${n}`, to: m, signal: 'cv', when: { id: `${m}.source`, in: LFO_WAVES } },
    {
      id: feg,
      from: 'env_f',
      to: m,
      signal: 'cv',
      when: {
        all: [
          { id: `${m}.source`, eq: 'feg_pgm' },
          { id: `${m}.pgmSrc`, eq: 'filter_eg' },
        ],
      },
    },
    {
      id: wheel,
      from: 'wheels',
      to: m,
      signal: 'cv',
      label: 'depth',
      levels: [{ id: `${m}.wheelDepth`, off: 0 }],
    },
    {
      id: vel,
      from: 'kbd',
      to: m,
      signal: 'cv',
      label: 'velocity',
      levels: [{ id: `${m}.velDepth`, off: 0 }],
    },
    {
      id: at,
      from: 'kbd',
      to: m,
      signal: 'cv',
      label: 'aftertouch',
      levels: [{ id: `${m}.atDepth`, off: 0 }],
    },
    {
      id: p1,
      from: m,
      to: 'osc1',
      signal: 'cv',
      label: 'pitch',
      when: { id: `${m}.pitchOsc`, in: ['both', 'osc1'] },
      levels: [{ id: `${m}.pitchAmt`, off: 0 }],
    },
    {
      id: p2,
      from: m,
      to: 'osc2',
      signal: 'cv',
      label: 'pitch',
      when: { id: `${m}.pitchOsc`, in: ['both', 'osc2'] },
      levels: [{ id: `${m}.pitchAmt`, off: 0 }],
    },
    {
      id: cut,
      from: m,
      to: 'vcf',
      signal: 'cv',
      label: 'cutoff',
      levels: [{ id: `${m}.filterAmt`, off: 0 }],
    },
    {
      id: rate,
      from: m,
      to: other,
      signal: 'cv',
      label: 'rate',
      when: dest(['lfo_rate']),
      levels: amt,
    },
    {
      id: vca,
      from: m,
      to: 'vca',
      signal: 'cv',
      label: 'level',
      when: dest(['vca_level']),
      levels: amt,
    },
    {
      id: w1,
      from: m,
      to: 'osc1',
      signal: 'cv',
      label: 'wave',
      when: dest(['osc1_wave', 'osc1_osc2_wave']),
      levels: amt,
    },
    {
      id: w2,
      from: m,
      to: 'osc2',
      signal: 'cv',
      label: 'wave',
      when: dest(['osc2_wave', 'osc1_osc2_wave']),
      levels: amt,
    },
    {
      id: noise,
      from: m,
      to: 'noise',
      signal: 'cv',
      label: 'level',
      when: dest(['noise_level']),
      levels: amt,
    },
    { id: tf, from: m, to: 'env_f', signal: 'cv', label: 'time', when: egTime, levels: amt },
    { id: ta, from: m, to: 'env_a', signal: 'cv', label: 'time', when: egTime, levels: amt },
    {
      id: reset,
      from: 'kbd',
      to: `lfo${n}`,
      signal: 'gate',
      label: 'reset',
      when: { id: `lfo${n}.kbReset`, eq: true },
    },
  ];
}

