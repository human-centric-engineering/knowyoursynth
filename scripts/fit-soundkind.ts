/**
 * Fit the sound detector's model to the library and write it to `lib/app/synths/lib/soundkind-model.ts`.
 *
 * Renders every library sound through the detector (`scripts/soundkind-sweep.ts`), fits the category weights and the
 * category-to-role shares (`lib/app/synths/lib/soundkind-fit.ts`), then prints what the doc records: the agreement
 * with the library's categories (on the sounds it was fitted to, and cross-validated), and the confusion table.
 *
 * Usage:
 *   npx tsx scripts/fit-soundkind.ts           fit, write the model, print the figures
 *   npx tsx scripts/fit-soundkind.ts --report  print the committed model's figures; write nothing
 *
 * Run it when the detector's features change or the library has grown, then update the figure the library test pins
 * (`soundkind-library.test.ts`) and the table in `.context/app/pattern-library.md`.
 *
 * Printing goes through `console`, not `logger` — see the `scripts/**` override in `eslint.config.mjs`.
 */
import { writeFileSync } from 'node:fs';
import { availableParallelism } from 'node:os';
import { join } from 'node:path';
import { format, resolveConfig } from 'prettier';
import { KIND_MODEL } from '@/lib/app/synths/lib/soundkind-model';
import {
  agreement,
  confusionMarkdown,
  crossValidate,
  fitKindModel,
} from '@/lib/app/synths/lib/soundkind-fit';
import { sweepLibrary } from '@/scripts/soundkind-sweep';

const MODEL_FILE = join(process.cwd(), 'lib', 'app', 'synths', 'lib', 'soundkind-model.ts');
const pct = (a: { agree: number; total: number }): string =>
  `${a.agree} / ${a.total} (${((100 * a.agree) / a.total).toFixed(1)}%)`;

async function main(): Promise<void> {
  const report = process.argv.includes('--report');
  const t0 = performance.now();
  const rows = await sweepLibrary(Math.max(1, availableParallelism() - 1));
  console.log(`read ${rows.length} sounds in ${((performance.now() - t0) / 1000).toFixed(0)} s`);

  const model = report ? KIND_MODEL : fitKindModel(rows);
  if (!report) {
    const source = `// Generated by \`npx tsx scripts/fit-soundkind.ts\` from the library's ${rows.length} sounds. Do not edit by hand:
// refit instead (.context/app/pattern-library.md, The sound detector).
import type { KindModel } from '@/lib/app/synths/lib/soundkind';

export const KIND_MODEL: KindModel = ${JSON.stringify(model)};
`;
    writeFileSync(
      MODEL_FILE,
      await format(source, { ...(await resolveConfig(MODEL_FILE)), filepath: MODEL_FILE })
    );
    console.log(`model written: lib/app/synths/lib/soundkind-model.ts`);
  }
  const fitted = agreement(rows, model);
  console.log(`agreement with the categories: ${pct(fitted)}`);
  console.log(`cross-validated (5 folds): ${pct(crossValidate(rows))}`);
  console.log(`\n${confusionMarkdown(fitted)}`);
  process.exit(0);
}

main().catch((err: unknown) => {
  console.error(err);
  process.exit(1);
});
